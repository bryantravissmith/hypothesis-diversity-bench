"""Offline, reproducible coverage experiments. No model calls or input edits.

    uv run validate_intervals.py --output results/validation

NumPy is used only by this validation program. Analysis remains stdlib-only.
Settings and seeds are recorded before simulation in validation-spec.json.
"""

import argparse
import hashlib
import json
import math
import platform
from pathlib import Path

import numpy as np

import intervals

ROOT = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def score_lookup(n, k):
    return np.array([1 if n - c < k else 1 - math.comb(n - c, k) / math.comb(n, k) for c in range(n + 1)])


def sample(setting, experiments, rng):
    p = np.array(setting["probabilities"])
    m, n, k = (setting[key] for key in ("cases", "repeats", "k"))
    lookup = score_lookup(n, k)
    if setting["tier"] == "none":
        # Each prompt can have its own category distribution; last category is a miss.
        counts = np.stack([rng.multinomial(n, probs, size=experiments) for probs in p], axis=1)
        scores = lookup[counts[:, :, :4]].sum(axis=2) / 4
        target = (1 - (1 - p[:, :4]) ** k).sum(axis=1).mean() / 4
    else:
        counts = rng.binomial(n, p, size=(experiments, m))
        scores = lookup[counts]
        target = (1 - (1 - p) ** k).mean()
    if setting.get("stress") == "one Bernoulli outcome shared by every job":
        scores = np.broadcast_to(rng.binomial(1, p[0], size=(experiments, 1)), (experiments, m))
    return scores, setting.get("target", float(target))


def bounds(scores, setting, alpha=.05):
    means = scores.mean(axis=1)
    unique, inverse = np.unique(means, return_inverse=True)
    limits = [intervals.fixed_prompt_interval(
        float(value), setting["cases"], setting["repeats"], setting["k"], setting["tier"], alpha,
    ) for value in unique]
    return np.array([b["low"] for b in limits])[inverse], np.array([b["high"] for b in limits])[inverse]


def wilson(successes, trials):
    """95% Wilson interval for Monte Carlo frequency, not the scientific CI."""
    z = 1.959963984540054
    p = successes / trials
    den = 1 + z * z / trials
    center = (p + z * z / (2 * trials)) / den
    radius = z * math.sqrt(p * (1 - p) / trials + z * z / (4 * trials * trials)) / den
    return [max(0, center - radius), min(1, center + radius)]


def metrics(low, high, truth):
    covered = (low <= truth + 1e-12) & (high >= truth - 1e-12)
    n, successes = len(covered), int(covered.sum())
    return dict(coverage=successes / n, monte_carlo_95=wilson(successes, n),
                average_width=float(np.mean(high - low)), experiments=n,
                width_monte_carlo_se=float(np.std(high - low, ddof=1) / math.sqrt(n)),
                monte_carlo_se=math.sqrt((successes / n) * (1 - successes / n) / n))


def markdown(result):
    lines = ["# Interval validation", "", "<!-- Generated by validate_intervals.py. Do not edit by hand. -->", "",
             f"Seed: {result['seed']}. Experiments per setting: {result['experiments']:,}. "
             "Each experiment draws a new complete dataset at the specified fixed prompts. "
             "Coverage is against the known fixed-prompt target. Parentheses show a 95% Wilson interval "
             "for Monte Carlo coverage.", "",
             "| Setting | Target | Coverage (MC interval) | Mean CI width |",
             "|---|---:|---|---:|"]

    def cov(m):
        a, b = m["monte_carlo_95"]
        return f"{m['coverage']:.4f} ({a:.4f}, {b:.4f})"

    for row in result["settings"]:
        m = row["interval"]
        lines.append(f"| {row['id']} | {row['target']:.4f} | {cov(m)} | {m['average_width']:.4f} |")
    lines += ["", "`stress-` rows deliberately violate independence or stationarity. Their failures are expected "
              "and are excluded from the undercoverage diagnostic.", "", "## Family-adjusted contrasts", "",
              "Six left-minus-right no-evidence pass@10 comparisons per family, each endpoint using six cases "
              "and 20 repeats. The 5% family error budget is split across 12 endpoint intervals. "
              "Coverage below means all six true differences were contained at once.", "",
              "| Family | Simultaneous coverage (MC interval) | Mean contrast width |",
              "|---|---|---:|"]
    for family in result["families"]:
        lines.append(f"| {family['id']} | {cov(family)} | {family['average_width']:.4f} |")
    lines += ["", "## Reproduction and limits", "",
              "The companion JSON contains every setting, exact input/source hashes, Python/NumPy versions, "
              "coverage, widths and Monte Carlo standard errors. `validation-spec.json` records all settings "
              "before simulation. Invalid responses occupy the fifth category in multinomial experiments. "
              "Heterogeneous correctness probabilities represent different case difficulties; relabeling truth "
              "categories leaves this score unchanged.", "",
              "The diagnostic fails if any in-scope coverage estimate is more than 0.005 below 0.95. "
              f"Diagnostic: **{result['diagnostic']}**.", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--spec", default=str(ROOT / "validation-spec.json"))
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    spec = json.loads(Path(args.spec).read_text())
    n = spec["experiments"]
    seeds = np.random.SeedSequence(spec["seed"]).spawn(len(spec["settings"]) + len(spec["contrast_families"]))
    result = dict(seed=spec["seed"], experiments=n, spec=spec, spec_sha256=sha(args.spec),
                  source_sha256={name: sha(ROOT / name) for name in ("intervals.py", "validate_intervals.py")},
                  python_version=platform.python_version(), numpy_version=np.__version__, settings=[], families=[])
    for setting, seed in zip(spec["settings"], seeds):
        draw_seed = seed.spawn(1)[0]
        scores, target = sample(setting, n, np.random.default_rng(draw_seed))
        interval = metrics(*bounds(scores, setting), target)
        result["settings"].append(dict(id=setting["id"], target=target, interval=interval, stress=setting.get("stress")))
        print(f"{setting['id']}: coverage {interval['coverage']:.4f}", flush=True)
    for family, seed in zip(spec["contrast_families"], seeds[len(spec["settings"]):]):
        lows, highs, truths = [], [], []
        for p, child in zip(family["probabilities"], seed.spawn(2 * family["pairs"])):
            setting = dict(tier="none", cases=6, repeats=20, k=10, probabilities=[p] * 6)
            scores, target = sample(setting, n, np.random.default_rng(child))
            lo, hi = bounds(scores, setting, .05 / (2 * family["pairs"]))
            lows.append(lo)
            highs.append(hi)
            truths.append(target)
        lo, hi = np.array(lows), np.array(highs)
        difference_low, difference_high = lo[::2] - hi[1::2], hi[::2] - lo[1::2]
        truth = (np.array(truths)[::2] - np.array(truths)[1::2])[:, None]
        covered = ((difference_low <= truth + 1e-12) & (difference_high >= truth - 1e-12)).all(axis=0)
        successes = int(covered.sum())
        result["families"].append(dict(id=family["id"], coverage=successes / n,
            monte_carlo_95=wilson(successes, n), experiments=n, endpoint_alpha=.05 / (2 * family["pairs"]),
            monte_carlo_se=math.sqrt((successes / n) * (1 - successes / n) / n),
            width_monte_carlo_se=float(np.std((difference_high - difference_low).mean(axis=0), ddof=1) / math.sqrt(n)),
            average_width=float(np.mean(difference_high - difference_low))))
        print(f"{family['id']}: simultaneous coverage {successes / n:.4f}", flush=True)
    rates = [r["interval"]["coverage"] for r in result["settings"] if not r["stress"]]
    rates += [r["coverage"] for r in result["families"]]
    result["diagnostic"] = "pass" if min(rates) >= .945 else "investigate undercoverage"
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    (output / "summary.json").write_text(json.dumps(result, indent=2) + "\n")
    (output / "VALIDATION.md").write_text(markdown(result))
    if result["diagnostic"] != "pass":
        raise SystemExit(result["diagnostic"])


if __name__ == "__main__":
    main()
